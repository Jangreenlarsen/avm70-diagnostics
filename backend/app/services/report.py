"""Diagnoserapport som struktureret engelsk tekstfil (FEATURES.md #12).

Rapporten er beregnet til at kunne sendes direkte til Anthem support:
faste sektioner i fast rækkefølge, identifikation og firmware øverst,
ren tekst (UTF-8, CRLF) der kan læses i enhver editor eller mail-klient.

Ren funktion over et `DeviceService.snapshot()` — ingen I/O — så den kan
testes uden en enhed.
"""

import re
from datetime import datetime, timezone

WIDTH = 78
LABEL_WIDTH = 40
EOL = "\r\n"

# Sektion 1-3: eksplicit rækkefølge, så det vigtigste for support står først.
IDENTIFICATION = ["IDM", "GCDN", "GSN", "IDQ", "IDR", "IDH"]
FIRMWARE = ["IDS", "DSPIDS", "LCDIDS", "IDB", "NMSVER", "NMHVER", "RVER", "RBD", "NMR"]
NETWORK = ["NMST", "EMAC", "WMAC", "GCTXS"]
OTHER_SYSTEM = ["GCFPB", "ICN"]
STATUS_GROUPS = [("zone1", "Zone 1"), ("audio", "Audio (zone 1)"), ("video", "Video (zone 1)"), ("zone2", "Zone 2")]

LOG_LIMIT = 200
TRAFFIC_LIMIT = 300

STATUS_TEXT = {
    "unknown": "not read",
    "invalid": "not supported (invalid command)",
    "out_of_range": "out of range",
    "cannot_execute": "cannot execute now",
    "zone_off": "zone is off",
    "timeout": "no response",
}


def _local(iso: str | None) -> str:
    if not iso:
        return "-"
    try:
        return datetime.fromisoformat(iso).astimezone().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
    except ValueError:
        return iso


def _rule(char: str = "-") -> str:
    return char * WIDTH


def _heading(number: int, title: str) -> list[str]:
    return ["", f"{number}. {title.upper()}", _rule()]


def _field(label: str, value: str) -> str:
    dots = "." * max(2, LABEL_WIDTH - len(label) - 1)
    return f"{label} {dots} {value}"


def _value_text(v: dict) -> str:
    """Afkodet værdi + rå værdi og kode i parentes, så support kan se
    præcis hvad enheden svarede, også når afkodningen er en fortolkning."""
    if v.get("raw") is None:
        text = STATUS_TEXT.get(v.get("status"), v.get("status") or "not read")
        return f"({text})  [{v['code']}]"
    raw = v["raw"]
    shown = "(not set)" if raw.strip() == "" else v.get("text") or raw
    suffix = f"[{v['code']}]" if shown == raw else f"[{v['code']} = {raw!r}]"
    line = f"{shown}  {suffix}"
    if v.get("status") not in ("ok", None):
        line += f"  ({STATUS_TEXT.get(v['status'], v['status'])} at last query)"
    return line


def _value_lines(values: dict[str, dict], codes: list[str]) -> list[str]:
    return [_field(values[c]["label"], _value_text(values[c])) for c in codes if c in values]


def _input_sort_key(code: str) -> tuple[int, int]:
    m = re.match(r"^IS(\d+)(IN|ARC)$", code)
    return (int(m.group(1)), 0 if m.group(2) == "IN" else 1) if m else (0, 0)


def report_filename(snapshot: dict, now: datetime) -> str:
    serial = next((v.get("raw") for v in snapshot["values"] if v["code"] == "GSN"), None) or ""
    serial = re.sub(r"[^A-Za-z0-9_-]", "", serial.strip()) or "unknown-serial"
    return f"AVM70_{serial}_{now.astimezone().strftime('%Y%m%d-%H%M%S')}.txt"


def build_report(snapshot: dict, app_version: dict, now: datetime, refreshed: bool,
                 refresh_error: str | None = None, probe: dict | None = None) -> str:
    """`now` skal være tidszone-bevidst (fx `datetime.now(timezone.utc)`)."""
    values = {v["code"]: v for v in snapshot["values"]}
    conn = snapshot["connection"]
    settings = snapshot["settings"]
    model = values.get("IDM", {}).get("raw") or "AVM 70"

    if refreshed:
        data_note = "All values re-queried from the device immediately before export"
    elif refresh_error:
        data_note = f"Re-query before export failed ({refresh_error}) - showing last known values"
    else:
        data_note = "Not connected - showing the last values read in this session"

    out: list[str] = [
        _rule("="),
        f" ANTHEM {model.upper()} - DIAGNOSTIC REPORT",
        _rule("="),
        _field("Generated", f"{now.astimezone().strftime('%Y-%m-%d %H:%M:%S %z')} "
                            f"({now.astimezone(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')})"),
        _field("System owner", settings.get("owner") or "-"),
        _field("Generated by", f"AVM70 Diagnostics v{app_version.get('version', '?')} build {app_version.get('build', '?')}"),
        _field("Device address", f"{conn['host']}:{conn['port']} (TCP, Anthem IP control protocol)"),
        _field("Connection", f"{conn['status']} since {_local(conn.get('since'))}"
               + (f" - last error: {conn['last_error']}" if conn.get("last_error") and conn["status"] != "connected" else "")),
        _field("Data", data_note),
        "",
        "Values are shown as decoded text, followed by the protocol code and the",
        "raw value returned by the device, e.g.  Dolby Surround  [Z1ALM = '3'].",
    ]

    out += _heading(1, "Device identification")
    out += _value_lines(values, IDENTIFICATION)

    out += _heading(2, "Firmware / versions")
    out += _value_lines(values, FIRMWARE)

    out += _heading(3, "Network")
    out += _value_lines(values, NETWORK)
    out.append(_field("IP address (as configured in app)", conn["host"]))

    out += _heading(4, "System & inputs")
    out += _value_lines(values, OTHER_SYSTEM)
    inputs = sorted((c for c, v in values.items() if v["group"] == "inputs"), key=_input_sort_key)
    out += _value_lines(values, inputs) if inputs else ["(input names not read)"]

    out += _heading(5, "Device settings")
    settings_codes = [c for c, v in values.items() if v["group"] == "settings"]
    out += _value_lines(values, settings_codes) if settings_codes else ["(settings not read)"]

    out += _heading(6, "Fault counters")
    faults = sorted((v for v in values.values() if v["group"] == "faults"), key=lambda v: v["code"])
    if not faults:
        out.append("(fault counters not read)")
    else:
        hw = faults[:8]
        cmd_nonzero = [v for v in faults[8:] if (v.get("raw") or "0").strip() not in ("0", "")]
        out.append("Read from the device's own fault register (FCC/FCN/FCQ). The meaning of each")
        out.append("counter is not publicly documented; hardware names are derived from the counter names.")
        out.append("")
        out.append("[Hardware]")
        out += _value_lines(values, [v["code"] for v in hw])
        out.append("")
        out.append(f"[Command fault counters - {len(cmd_nonzero)} of {len(faults) - len(hw)} not zero]")
        out += _value_lines(values, [v["code"] for v in cmd_nonzero]) or ["(all zero)"]

    out += _heading(7, "Current status")
    for group, title in STATUS_GROUPS:
        out.append(f"[{title}]")
        out += _value_lines(values, [c for c, v in values.items() if v["group"] == group])
        out.append("")
    out.pop()

    out += _heading(8, "Command support (probe)")
    if probe:
        rows = probe["results"]
        ok = sum(1 for r in rows if r["status"] == "ok")
        out.append(f"Probe run at {_local(probe['at'])}: {ok} of {len(rows)} commands answered.")
        out.append("")
        out.append(f"{'CODE':<9}{'RESULT':<34}MEANING")
        group_titles = snapshot.get("groups", {})
        for r in rows:
            result = "OK" if r["status"] == "ok" else STATUS_TEXT.get(r["status"], r["status"])
            group = group_titles.get(r.get("group"), "")
            meaning = f"{r['label']} ({group})" if group and r.get("group") not in ("system", "version", "inputs", "settings", "faults") else r["label"]
            out.append(f"{r['code']:<9}{result:<34}{meaning}")
    else:
        out.append("No probe has been run in this session (Console & probe > Run probe).")

    log = snapshot["log"][-LOG_LIMIT:]
    out += _heading(9, f"Event log (last {len(log)} entries, oldest first)")
    for e in log:
        source = f" [{e['source']}]" if e.get("source") else ""
        out.append(f"{_local(e['ts'])}  {e['kind'].upper():<10}{source} {e['text']}")
    if not log:
        out.append("(empty)")

    traffic = snapshot["traffic"][-TRAFFIC_LIMIT:]
    out += _heading(10, f"Raw protocol traffic (last {len(traffic)} lines, oldest first)")
    out.append("TX = sent by this app, RX = received from the device; [push] = unsolicited.")
    out.append("")
    for t in traffic:
        direction = "TX ->" if t["dir"] == "tx" else "RX <-"
        tag = " [push]" if t["dir"] == "rx" and t["origin"] == "push" else ""
        out.append(f"{_local(t['ts'])}  {direction} {t['line']};{tag}")
    if not traffic:
        out.append("(empty)")

    out += _heading(11, "App settings")
    for key in ("host", "port", "poll_interval", "connect_timeout", "query_timeout", "auto_reconnect",
                "auto_connect", "log_poll_interval", "owner"):
        out.append(_field(key, str(settings.get(key))))

    out += ["", _rule("="), " END OF REPORT", _rule("="), ""]
    return EOL.join(out)
